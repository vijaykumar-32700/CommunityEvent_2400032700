package com.klef.soa.docker.controller;

import java.util.List;
import java.util.Optional;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.CrossOrigin;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PatchMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

import com.klef.soa.docker.dto.CommunityEventRequestDTO;
import com.klef.soa.docker.dto.CommunityEventResponseDTO;
import com.klef.soa.docker.service.CommunityEventService;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.responses.ApiResponses;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;

@RestController
@CrossOrigin(origins = "*")
@Tag(name = "Community Event Management Controller", description = "Endpoints for managing community events")
public class CommunityEventController {

    @Autowired
    private CommunityEventService communityEventService;

    // ──────────────────────────────────────────────────────────────
    // EXAM-REQUIRED ENDPOINTS
    // ──────────────────────────────────────────────────────────────

    @GetMapping("/")
    @Operation(summary = "Health Check", description = "Returns service status confirmation")
    @ApiResponses({ @ApiResponse(responseCode = "200", description = "Service is running") })
    public ResponseEntity<String> healthCheck() {
        return ResponseEntity.ok("CRUD Service is running | Community Event Management | ID: 2400032700");
    }

    @PostMapping("/Add")
    @Operation(summary = "Add Community Event", description = "Adds a new event. ID is auto-generated by the database.")
    @ApiResponses({
        @ApiResponse(responseCode = "201", description = "Event added successfully"),
        @ApiResponse(responseCode = "400", description = "Validation failed")
    })
    public ResponseEntity<CommunityEventResponseDTO> addEvent(@Valid @RequestBody CommunityEventRequestDTO requestDTO) {
        CommunityEventResponseDTO created = communityEventService.addEvent(requestDTO);
        return new ResponseEntity<>(created, HttpStatus.CREATED);
    }

    @GetMapping("/DisplayAll")
    @Operation(summary = "Display All Events", description = "Returns all community events as a JSON list")
    @ApiResponses({ @ApiResponse(responseCode = "200", description = "Successfully retrieved all events") })
    public ResponseEntity<List<CommunityEventResponseDTO>> displayAll() {
        return ResponseEntity.ok(communityEventService.getAllEvents());
    }

    @DeleteMapping("/Delete/{id}")
    @Operation(summary = "Delete Event", description = "Deletes a community event by ID")
    @ApiResponses({
        @ApiResponse(responseCode = "200", description = "Event deleted successfully"),
        @ApiResponse(responseCode = "404", description = "Event not found")
    })
    public ResponseEntity<String> deleteEvent(
            @Parameter(description = "ID of the event to delete") @PathVariable Long id) {
        communityEventService.deleteEvent(id);
        return ResponseEntity.ok("Community event deleted successfully. Deleted ID: " + id);
    }

    // ──────────────────────────────────────────────────────────────
    // ADDITIONAL FRONTEND ENDPOINTS
    // ──────────────────────────────────────────────────────────────

    @PostMapping("/api/events")
    @Operation(summary = "Create Event", description = "Creates a new community event")
    @ApiResponses({
        @ApiResponse(responseCode = "201", description = "Event created"),
        @ApiResponse(responseCode = "400", description = "Validation failed")
    })
    public ResponseEntity<CommunityEventResponseDTO> createEvent(@Valid @RequestBody CommunityEventRequestDTO requestDTO) {
        return new ResponseEntity<>(communityEventService.addEvent(requestDTO), HttpStatus.CREATED);
    }

    @GetMapping("/api/events")
    @Operation(summary = "Get All Events", description = "Returns all events with optional filter and search")
    @ApiResponses({ @ApiResponse(responseCode = "200", description = "Events retrieved") })
    public ResponseEntity<List<CommunityEventResponseDTO>> getAllEvents(
            @Parameter(description = "Filter by completion status") @RequestParam(required = false) Boolean completed,
            @Parameter(description = "Search by name or venue") @RequestParam(required = false) String search) {
        return ResponseEntity.ok(communityEventService.getAllEvents(completed, search));
    }

    @GetMapping("/api/events/{id}")
    @Operation(summary = "Get Event by ID", description = "Returns a single event by its ID")
    @ApiResponses({
        @ApiResponse(responseCode = "200", description = "Event found"),
        @ApiResponse(responseCode = "404", description = "Event not found")
    })
    public ResponseEntity<CommunityEventResponseDTO> getEventById(
            @Parameter(description = "Event ID") @PathVariable Long id) {
        Optional<CommunityEventResponseDTO> event = communityEventService.getEventById(id);
        return event.map(ResponseEntity::ok)
                    .orElse(ResponseEntity.notFound().build());
    }

    @PutMapping("/api/events/{id}")
    @Operation(summary = "Update Event", description = "Updates an existing community event")
    @ApiResponses({
        @ApiResponse(responseCode = "200", description = "Event updated"),
        @ApiResponse(responseCode = "400", description = "Validation failed"),
        @ApiResponse(responseCode = "404", description = "Event not found")
    })
    public ResponseEntity<CommunityEventResponseDTO> updateEvent(
            @Parameter(description = "Event ID") @PathVariable Long id,
            @Valid @RequestBody CommunityEventRequestDTO requestDTO) {
        return ResponseEntity.ok(communityEventService.updateEvent(id, requestDTO));
    }

    @DeleteMapping("/api/events/{id}")
    @Operation(summary = "Delete Event (API)", description = "Deletes an event by ID")
    @ApiResponses({
        @ApiResponse(responseCode = "200", description = "Event deleted"),
        @ApiResponse(responseCode = "404", description = "Event not found")
    })
    public ResponseEntity<String> deleteEventApi(
            @Parameter(description = "Event ID") @PathVariable Long id) {
        communityEventService.deleteEvent(id);
        return ResponseEntity.ok("Community event deleted successfully. ID: " + id);
    }

    @PatchMapping("/api/events/{id}/toggle-status")
    @Operation(summary = "Toggle Event Status", description = "Toggles event between completed and upcoming")
    @ApiResponses({
        @ApiResponse(responseCode = "200", description = "Status toggled"),
        @ApiResponse(responseCode = "404", description = "Event not found")
    })
    public ResponseEntity<CommunityEventResponseDTO> toggleStatus(
            @Parameter(description = "Event ID") @PathVariable Long id) {
        return ResponseEntity.ok(communityEventService.toggleStatus(id));
    }
}
