package com.klef.soa.docker.controller;

import com.klef.soa.docker.dto.ApiResponseDTO;
import com.klef.soa.docker.dto.CommunityEventRequestDTO;
import com.klef.soa.docker.dto.CommunityEventResponseDTO;
import com.klef.soa.docker.service.CommunityEventService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.responses.ApiResponses;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.CrossOrigin;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.PatchMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

import java.util.List;

/**
 * REST Controller for CommunityEvent entity.
 * Exposes EXACT exam-required endpoints AND additional frontend-friendly endpoints.
 * Base package: com.klef.soa.docker.controller
 * Student ID: 2400032700 | Name: UMMADI VIJAY KUMAR | Section: S51
 *
 * Exam-required endpoints:
 *   GET    /              → Health check
 *   POST   /Add           → Add new community event
 *   GET    /DisplayAll    → Display all community events
 *   DELETE /Delete/{id}   → Delete community event by ID
 *
 * Additional endpoints for frontend:
 *   GET    /api/events         → Get all (with optional filter/search)
 *   GET    /api/events/{id}    → Get by ID
 *   PUT    /api/events/{id}    → Update event
 *   DELETE /api/events/{id}    → Delete event
 *   PATCH  /api/events/{id}/toggle-status → Toggle completion
 */
@RestController
@CrossOrigin(origins = "*", allowedHeaders = "*")
@Tag(name = "Community Events API",
     description = "Operations for adding, viewing, updating, and deleting community events | Student: 2400032700")
public class CommunityEventController {

    private final CommunityEventService eventService;

    @Autowired
    public CommunityEventController(CommunityEventService eventService) {
        this.eventService = eventService;
    }

    // ============================================================
    // EXAM-REQUIRED ENDPOINTS
    // ============================================================

    /**
     * GET / — Health check endpoint.
     * Returns a simple string confirming the CRUD service is running.
     */
    @GetMapping("/")
    @Operation(
        summary = "Health Check",
        description = "Returns a message confirming the CRUD Service is running. Exam required endpoint: GET /"
    )
    @ApiResponses(value = {
        @ApiResponse(responseCode = "200", description = "Service is running")
    })
    public ResponseEntity<String> healthCheck() {
        return ResponseEntity.ok(
            "CRUD Service is running | Community Event Management System | Student: 2400032700 | UMMADI VIJAY KUMAR"
        );
    }

    /**
     * POST /Add — Add a new community event.
     * ID is auto-generated by the database; do NOT provide id in the request body.
     */
    @PostMapping("/Add")
    @Operation(
        summary = "Add Community Event",
        description = "Adds a new community event record. ID is automatically generated by the database — do NOT send id in request body. Exam required endpoint: POST /Add"
    )
    @ApiResponses(value = {
        @ApiResponse(responseCode = "201", description = "Community event added successfully"),
        @ApiResponse(responseCode = "400", description = "Validation failed for the request body")
    })
    public ResponseEntity<ApiResponseDTO<CommunityEventResponseDTO>> addEvent(
            @Valid @RequestBody CommunityEventRequestDTO requestDTO) {
        CommunityEventResponseDTO created = eventService.createEvent(requestDTO);
        return new ResponseEntity<>(
                ApiResponseDTO.success(
                    "Community event added successfully. Auto-generated ID: " + created.getId(),
                    created
                ),
                HttpStatus.CREATED
        );
    }

    /**
     * GET /DisplayAll — Retrieve all community events.
     * Returns the full list of community events stored in the database.
     */
    @GetMapping("/DisplayAll")
    @Operation(
        summary = "Display All Community Events",
        description = "Returns a JSON list of all saved community events, including their auto-generated IDs. Exam required endpoint: GET /DisplayAll"
    )
    @ApiResponses(value = {
        @ApiResponse(responseCode = "200", description = "Successfully retrieved all community events")
    })
    public ResponseEntity<List<CommunityEventResponseDTO>> displayAllEvents() {
        List<CommunityEventResponseDTO> events = eventService.getAllEvents(null, null);
        return ResponseEntity.ok(events);
    }

    /**
     * DELETE /Delete/{id} — Delete a community event by ID.
     * Handles non-existent IDs gracefully with a 404 error response.
     */
    @DeleteMapping("/Delete/{id}")
    @Operation(
        summary = "Delete Community Event",
        description = "Deletes the community event matching the given ID. Returns a confirmation message. Handles non-existent IDs appropriately. Exam required endpoint: DELETE /Delete/{id}"
    )
    @ApiResponses(value = {
        @ApiResponse(responseCode = "200", description = "Community event deleted successfully"),
        @ApiResponse(responseCode = "404", description = "Community event with given ID not found")
    })
    public ResponseEntity<ApiResponseDTO<Void>> deleteEventByExamEndpoint(
            @Parameter(description = "Auto-generated ID of the community event to delete")
            @PathVariable Long id) {
        eventService.deleteEvent(id);
        return ResponseEntity.ok(
            ApiResponseDTO.success("Community event deleted successfully. Deleted ID: " + id, null)
        );
    }

    // ============================================================
    // ADDITIONAL FRONTEND-FACING ENDPOINTS (under /api/events)
    // ============================================================

    @PostMapping("/api/events")
    @Operation(summary = "Create Event (Frontend API)", description = "Creates a new community event. ID auto-generated.")
    @ApiResponses(value = {
        @ApiResponse(responseCode = "201", description = "Event created"),
        @ApiResponse(responseCode = "400", description = "Validation failed")
    })
    public ResponseEntity<ApiResponseDTO<CommunityEventResponseDTO>> createEvent(
            @Valid @RequestBody CommunityEventRequestDTO requestDTO) {
        CommunityEventResponseDTO created = eventService.createEvent(requestDTO);
        return new ResponseEntity<>(
                ApiResponseDTO.success("Community event created successfully with generated ID: " + created.getId(), created),
                HttpStatus.CREATED
        );
    }

    @GetMapping("/api/events")
    @Operation(summary = "Get All Events (Frontend API)", description = "Fetches all community events with optional filters.")
    @ApiResponses(value = {
        @ApiResponse(responseCode = "200", description = "Successfully retrieved list of events")
    })
    public ResponseEntity<List<CommunityEventResponseDTO>> getAllEvents(
            @Parameter(description = "Filter by completion status (true/false)")
            @RequestParam(required = false) Boolean completed,
            @Parameter(description = "Search keyword in event name or venue")
            @RequestParam(required = false) String search) {
        List<CommunityEventResponseDTO> events = eventService.getAllEvents(completed, search);
        return ResponseEntity.ok(events);
    }

    @GetMapping("/api/events/{id}")
    @Operation(summary = "Get Event by ID (Frontend API)", description = "Returns a single event by ID.")
    @ApiResponses(value = {
        @ApiResponse(responseCode = "200", description = "Event found"),
        @ApiResponse(responseCode = "404", description = "Event not found")
    })
    public ResponseEntity<CommunityEventResponseDTO> getEventById(
            @Parameter(description = "ID of the community event") @PathVariable Long id) {
        return ResponseEntity.ok(eventService.getEventById(id));
    }

    @PutMapping("/api/events/{id}")
    @Operation(summary = "Update Event (Frontend API)", description = "Updates an existing community event by ID.")
    @ApiResponses(value = {
        @ApiResponse(responseCode = "200", description = "Event updated successfully"),
        @ApiResponse(responseCode = "400", description = "Validation failed"),
        @ApiResponse(responseCode = "404", description = "Event not found")
    })
    public ResponseEntity<ApiResponseDTO<CommunityEventResponseDTO>> updateEvent(
            @Parameter(description = "ID of the event to update") @PathVariable Long id,
            @Valid @RequestBody CommunityEventRequestDTO requestDTO) {
        CommunityEventResponseDTO updated = eventService.updateEvent(id, requestDTO);
        return ResponseEntity.ok(ApiResponseDTO.success("Community event updated successfully", updated));
    }

    @DeleteMapping("/api/events/{id}")
    @Operation(summary = "Delete Event (Frontend API)", description = "Deletes an event permanently by ID.")
    @ApiResponses(value = {
        @ApiResponse(responseCode = "200", description = "Event deleted successfully"),
        @ApiResponse(responseCode = "404", description = "Event not found")
    })
    public ResponseEntity<ApiResponseDTO<Void>> deleteEvent(
            @Parameter(description = "ID of the event to delete") @PathVariable Long id) {
        eventService.deleteEvent(id);
        return ResponseEntity.ok(
            ApiResponseDTO.success("Community event deleted successfully with ID: " + id, null)
        );
    }

    @PatchMapping("/api/events/{id}/toggle-status")
    @Operation(summary = "Toggle Event Status (Frontend API)", description = "Switches event between completed and upcoming.")
    @ApiResponses(value = {
        @ApiResponse(responseCode = "200", description = "Status updated"),
        @ApiResponse(responseCode = "404", description = "Event not found")
    })
    public ResponseEntity<ApiResponseDTO<CommunityEventResponseDTO>> toggleStatus(
            @Parameter(description = "ID of the event to toggle") @PathVariable Long id) {
        CommunityEventResponseDTO updated = eventService.toggleStatus(id);
        return ResponseEntity.ok(
            ApiResponseDTO.success(
                "Event status updated to " + (Boolean.TRUE.equals(updated.getCompleted()) ? "Completed" : "Upcoming"),
                updated
            )
        );
    }
}
